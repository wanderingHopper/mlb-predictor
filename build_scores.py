"""Reproduce Ryan's *final combined model* from Matchup_Predictor.ipynb.

No third-party packages required. Generates scores.js for the static website.
Normalization (min-max) uses all 30 teams, just like Ryan's notebook.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'source'

OFFENSE_WEIGHTS = {
    'R/G': .40, 'OPS': .10, 'SLG': .10, 'OPS+': .10,
    'HR': .10, 'BB': .05, 'SO': -.05, 'SB': .05, 'BA': .15,
}
PITCHING_WEIGHTS = {
    'RA/G': .25, 'ERA': .25, 'ERA+': .15, 'FIP': .10,
    'WHIP': .10, 'H9': .05, 'HR9': .03, 'BB9': .02, 'SO9': .05,
}
INVERSE_PITCHING = {'RA/G', 'ERA', 'FIP', 'WHIP', 'H9', 'HR9', 'BB9'}


def read_teams(path, *, skip_first_line=False):
    with path.open(encoding='utf-8-sig', newline='') as f:
        if skip_first_line:
            next(f)
        return [
            row for row in csv.DictReader(f)
            if row.get('Tm', '').strip() not in ('', 'League Average', 'League Totals')
        ]


def calculate(rows, weights, inverse=frozenset()):
    columns = {}
    for col in weights:
        values = [float(r[col]) for r in rows]
        lo, hi = min(values), max(values)
        columns[col] = [
            (1 - ((v - lo) / (hi - lo)) if col in inverse else ((v - lo) / (hi - lo)))
            if hi != lo else 0.0
            for v in values
        ]
    return {
        row['Tm'].strip(): sum(columns[col][i] * weight for col, weight in weights.items())
        for i, row in enumerate(rows)
    }


batting = calculate(
    read_teams(SOURCE / 'A - MLB STATS.csv'),
    OFFENSE_WEIGHTS,
)
pitching = calculate(
    read_teams(SOURCE / 'mlb_team_pitching_statistics.csv'),
    PITCHING_WEIGHTS,
    inverse=INVERSE_PITCHING,
)

# Same inner merge and 55/45 combination as the final notebook cell.
# Both inputs are cleaned 2026 regular-season team totals (30 teams).
assert set(batting) == set(pitching), 'Batting and pitching team lists do not match'
teams = []
for name in batting:
    if name in pitching:
        offense, pitching_score = batting[name], pitching[name]
        teams.append({
            'name': name,
            'offense': round(offense, 12),
            'pitching': round(pitching_score, 12),
            'total': round(offense * .55 + pitching_score * .45, 12),
        })
assert len(teams) == 30, f'Expected 30 teams, got {len(teams)}'
lookup = {team['name']: team['total'] for team in teams}
mets = lookup['New York Mets']
yankees = lookup['New York Yankees']
assert mets + yankees > 0, 'Yankees/Mets model scores must be positive'

result = '/* Generated by build_scores.py from 2026 regular-season CSV files. */\n'
result += 'window.TEAM_SCORES = ' + json.dumps(teams, indent=2, ensure_ascii=False) + ';\n'
(ROOT / 'scores.js').write_text(result, encoding='utf-8')
print('Generated 2026 scores.js for', len(teams), 'teams. Yankees–Mets:',
      round(100 * yankees / (mets + yankees), 1), '% /',
      round(100 * mets / (mets + yankees), 1), '%')


# Browser-side feature data for interactive weight experiments.
# Uses the same min-max transformation as the original final notebook.
def feature_columns(rows, names, inverse=frozenset()):
    columns = {}
    for col in names:
        values = [float(r[col]) for r in rows]
        lo, hi = min(values), max(values)
        columns[col] = [
            (1 - ((v - lo) / (hi - lo)) if col in inverse else (v - lo) / (hi - lo))
            if hi != lo else 0.0
            for v in values
        ]
    return {row['Tm'].strip(): [round(columns[col][i], 12) for col in names] for i, row in enumerate(rows)}

offense_names = list(OFFENSE_WEIGHTS)
pitching_names = list(PITCHING_WEIGHTS)
feature_batting = feature_columns(
    read_teams(SOURCE / 'A - MLB STATS.csv'), offense_names
)
feature_pitching = feature_columns(
    read_teams(SOURCE / 'mlb_team_pitching_statistics.csv'), pitching_names, INVERSE_PITCHING
)
features = {
    'offenseStats': offense_names,
    'pitchingStats': pitching_names,
    'defaultOffense': list(OFFENSE_WEIGHTS.values()),
    'defaultPitching': list(PITCHING_WEIGHTS.values()),
    'teams': {name: {'offense': feature_batting[name], 'pitching': feature_pitching[name]}
              for name in feature_batting if name in feature_pitching},
}
assert len(features['teams']) == 30
for t in teams:
    v = features['teams'][t['name']]
    off = sum(a*b for a,b in zip(v['offense'], features['defaultOffense']))
    pit = sum(a*b for a,b in zip(v['pitching'], features['defaultPitching']))
    assert abs(off-t['offense']) < 1e-9 and abs(pit-t['pitching']) < 1e-9
(ROOT / 'features.js').write_text(
    '/* 2026 normalized feature data generated by build_scores.py; no backend required. */\n'
    + 'window.MODEL_FEATURES = ' + json.dumps(features, separators=(',', ':'), ensure_ascii=False) + ';\n',
    encoding='utf-8'
)
print('Generated features.js; all 30 original scores verified.')
